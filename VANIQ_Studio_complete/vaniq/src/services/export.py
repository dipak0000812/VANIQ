"""Dataset export with permission gating.

Public export  : permission_status == granted AND permitted_usage == public_release AND verified.
Internal export: permission_status == granted (private_research / internal_training / public_release) AND verified.
UNKNOWN or denied permissions are NEVER included in a public export, and denied is never exported at all.
Unknown permission can enter an *internal* export only with an explicit flag, and the manifest records it.
"""
from __future__ import annotations

import csv
import hashlib
import json
import os
import shutil
import zipfile
from datetime import datetime, timezone

from src.baseline import NATIVE_SUPPORT_STATEMENT, sanitize_provider_response
from src.context import AppContext
from src.correction import apply_suggestions
from src.services.errors import ServiceError

DATASET_CARD = """# {name}

Generated by VANIQ on {ts} (mode: {mode}).

{synthetic_banner}## Contents
* clips: {n} audio clips (mono, 16 kHz, 16-bit PCM WAV) in `audio/`
* `metadata.jsonl` / `metadata.csv`: one record per clip
* `manifest.json`: selection rules and counts, including what was excluded and why

## Selection rules
* visibility: **{visibility}**
* only clips with a human-verified reference transcript{unknown_note}
* clips with permission 'denied' are never exported

## Fields
`reference_transcript` is human verified. `raw_transcript` is unedited STT output and is NOT ground truth.
`corrected_transcript` is raw text plus human-accepted corrections. `dialect_label` is a human-assigned label.

## STT results
{stt_note}
Transcripts with `experiment_role: baseline` are provider baseline experiments. `detected_language_code_by_stt` is the
provider's language detection, not the speaker's declared dialect.

## Limitations
Small, speaker-limited dataset. No train/test split is provided. Spelling conventions for the dialect are not
standardised. Do not use this data to claim broad language coverage.
"""


def clip_exclusion_reason(c: dict, visibility: str, include_unknown_internal: bool = False,
                          require_verified: bool = True) -> str | None:
    """Single source of truth for export eligibility. Returns the exclusion reason key, or None if eligible."""
    if c["review_status"] == "rejected":
        return "rejected_clip"
    if c["permission_status"] == "denied":
        return "permission_denied"
    if c["permission_status"] != "granted" or c["permitted_usage"] == "UNKNOWN":
        if not (visibility == "internal" and include_unknown_internal):
            return "permission_unknown"
    elif visibility == "public" and c["permitted_usage"] != "public_release":
        return "usage_not_public"
    if require_verified and (c["review_status"] != "verified" or not c.get("reference_transcript")):
        return "not_verified"
    return None


def select_clips(ctx: AppContext, visibility: str, include_unknown_internal: bool = False,
                 require_verified: bool = True, clip_ids: list[str] | None = None) -> tuple[list[dict], dict]:
    if visibility not in ("public", "internal"):
        raise ServiceError("visibility must be 'public' or 'internal'.", "bad_visibility", 422)
    if visibility == "public" and include_unknown_internal:
        raise ServiceError("Unknown-permission recordings can never be part of a public export.",
                           "unknown_in_public", 422)
    wanted = set(clip_ids) if clip_ids is not None else None
    selected, excluded = [], {"permission_denied": 0, "permission_unknown": 0, "usage_not_public": 0,
                              "not_verified": 0, "rejected_clip": 0}
    for c in ctx.repo.list_clips():
        if wanted is not None and c["id"] not in wanted:
            continue
        reason = clip_exclusion_reason(c, visibility, include_unknown_internal, require_verified)
        if reason:
            excluded[reason] += 1
        else:
            selected.append(c)
    return selected, excluded


def export_dataset(ctx: AppContext, visibility: str = "public", include_unknown_internal: bool = False,
                   require_verified: bool = True, name: str = "vaniq-dataset", clip_ids: list[str] | None = None) -> dict:
    clips, excluded = select_clips(ctx, visibility, include_unknown_internal, require_verified, clip_ids)
    ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    safe = "".join(ch for ch in name if ch.isalnum() or ch in "-_")[:40] or "vaniq-dataset"
    out_dir = ctx.settings.exports_dir / f"{safe}-{visibility}-{ts}"
    (out_dir / "audio").mkdir(parents=True, exist_ok=True)

    anonymize = visibility == "public"
    records = []
    for c in clips:
        fname = f"{c['id']}.wav"
        shutil.copyfile(c["path"], out_dir / "audio" / fname)
        transcripts = []
        for t in ctx.repo.list_transcripts(c["id"]):
            sugg = ctx.repo.list_suggestions(t["id"])
            entry = {
                "provider": t["provider"], "model": t["model"], "is_synthetic": bool(t["is_synthetic"]),
                "experiment_role": t["experiment_role"],
                "language_code_requested": t["language_code_requested"],
                "detected_language_code_by_stt": t["detected_language_code"],
                "raw_transcript": t["transcript_raw"],
                "corrected_transcript": apply_suggestions(t["transcript_raw"], sugg),
                "accepted_corrections": [
                    {"original": s["original"], "final": s["final_replacement"] if s["status"] == "modified" else s["replacement"],
                     "kind": s["kind"], "backend": s["backend"], "decided_by": s["decided_by"] if not anonymize else None}
                    for s in sugg if s["status"] in ("accepted", "modified")]}
            if visibility == "internal":
                # Provider body only (never request headers/credentials), sanitised as defence in depth.
                entry["provider_response"] = sanitize_provider_response(t.get("raw_response"), [ctx.settings.gnani_api_key])
            transcripts.append(entry)
        speaker = c["speaker_id"]
        if anonymize and speaker != "UNKNOWN":
            speaker = "spk_" + hashlib.sha256(speaker.encode()).hexdigest()[:8]
        records.append({
            "clip_id": c["id"], "audio_file": f"audio/{fname}", "duration_s": c["duration_s"],
            "speaker_id": speaker, "dialect_label": c["dialect_label"],
            "permission_status": c["permission_status"], "permitted_usage": c["permitted_usage"],
            "rms_dbfs": c["rms_dbfs"], "peak_dbfs": c["peak_dbfs"], "clipping_count": c["clipping_count"],
            "silence_ratio": c["silence_ratio"], "review_status": c["review_status"],
            "reference_transcript": c.get("reference_transcript"),
            "reference_verified_by": None if anonymize else c.get("reference_by"),
            "synthetic_demo": bool(c["is_demo"]), "transcripts": transcripts})

    with open(out_dir / "metadata.jsonl", "w", encoding="utf-8") as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    flat_fields = ["clip_id", "audio_file", "duration_s", "speaker_id", "dialect_label", "permission_status",
                   "permitted_usage", "review_status", "reference_transcript", "raw_transcript", "corrected_transcript",
                   "synthetic_demo"]
    with open(out_dir / "metadata.csv", "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=flat_fields)
        w.writeheader()
        for r in records:
            t = r["transcripts"][-1] if r["transcripts"] else {}
            w.writerow({**{k: r[k] for k in flat_fields if k in r},
                        "raw_transcript": t.get("raw_transcript", ""), "corrected_transcript": t.get("corrected_transcript", "")})

    manifest = {"name": safe, "created_at": ts, "mode": ctx.settings.mode, "visibility": visibility,
                "synthetic_demo_data": ctx.settings.is_demo, "clip_count": len(records),
                "require_verified": require_verified, "include_unknown_permission": include_unknown_internal,
                "excluded_counts": excluded, "speakers_anonymized": anonymize,
                "provider_responses_included": visibility == "internal",
                "stt_results_note": NATIVE_SUPPORT_STATEMENT}
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    banner = ("> **SYNTHETIC DEMO DATA.** Generated in demo mode; audio is synthetic tones and transcripts are "
              "placeholders. Not a real dataset.\n\n") if ctx.settings.is_demo else ""
    (out_dir / "DATASET_CARD.md").write_text(DATASET_CARD.format(
        name=safe, ts=ts, mode=ctx.settings.mode, n=len(records), visibility=visibility, synthetic_banner=banner,
        unknown_note=" (unknown-permission clips INCLUDED by explicit request)" if include_unknown_internal else "",
        stt_note=NATIVE_SUPPORT_STATEMENT),
        encoding="utf-8")

    zip_path = str(out_dir) + ".zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for root, _, files in os.walk(out_dir):
            for fn in files:
                full = os.path.join(root, fn)
                z.write(full, os.path.relpath(full, out_dir))
    ctx.repo.audit("system", "export_dataset", "dataset", safe, manifest)
    return {"zip_path": zip_path, "directory": str(out_dir), "manifest": manifest}
