logger = logging.getLogger(__name__)

DEMO_LEXICON = [
    ("dform1", "sform1", "", ""),
    ("dform2", "sform2", "", ""),
    ("dform3", "sform3", "also", ""),
    ("dform4", "sform4", "", "beta"),
]
_GOLD = {"dform1": "sform1", "dform3": "sform3", "dform4": "sform4"}  # dform2 is deliberately correct as-is
_SOURCES = [  # (speaker, permission, usage)
    ("demo-spk-1", "granted", "public_release"),
    ("demo-spk-1", "granted", "public_release"),
    ("demo-spk-2", "granted", "public_release"),
    ("demo-spk-2", "granted", "private_research"),
    ("demo-spk-3", "UNKNOWN", "UNKNOWN"),
    ("demo-spk-3", "granted", "public_release"),
]


def synth_wav(path: str, freq: float, bursts: int = 2, burst_s: float = 1.2, gap_s: float = 0.7, sr: int = 16000) -> None:
    """Deterministic tone bursts separated by silence (NOT speech)."""
    t = np.linspace(0, burst_s, int(sr * burst_s), endpoint=False)
    tone = (np.sin(2 * np.pi * freq * t) * 0.4 * 32767).astype(np.int16)
    gap = np.zeros(int(sr * gap_s), dtype=np.int16)
    parts = [gap]
    for _ in range(bursts):
        parts += [tone, gap]
    wavfile.write(path, sr, np.concatenate(parts))


def seed_demo(ctx: AppContext) -> dict:
    if not ctx.settings.is_demo:
        raise ServiceError("Demo data can only be seeded when VANIQ_MODE=demo.", "not_demo_mode", 409)
    if ctx.repo.list_sources():
        return {"seeded": False, "reason": "demo data already present", **ctx.repo.counts()}

    for src, tgt, prev, nxt in DEMO_LEXICON:
        ctx.repo.add_lexicon_entry({
            "source_form": src, "target_form": tgt, "context_prev": prev, "context_next": nxt, "status": "demo",
            "provenance": "SYNTHETIC DEMO ENTRY - not real Ahirani/Marathi", "is_demo": 1,
            "notes": "Placeholder used to demonstrate the correction workflow."}, actor="demo-seed")

    with tempfile.TemporaryDirectory() as tmp:
        for i, (spk, perm, usage) in enumerate(_SOURCES):
            p = os.path.join(tmp, f"demo_recording_{i + 1}.wav")
            synth_wav(p, freq=300 + 90 * i)
            ingest_file(ctx, p, os.path.basename(p), speaker_id=spk, dialect_label="DEMO-SYNTHETIC",
                        permission_status=perm, permitted_usage=usage,
                        consent_notes="Synthetic audio generated by VANIQ; no real speaker.", actor="demo-seed")

    clips = sorted(ctx.repo.list_clips(), key=lambda c: (c["source_id"], c["start_s"]))
    for idx, clip in enumerate(clips):
        t = transcribe_clip(ctx, clip["id"], "indic-auto", actor="demo-seed")
        if idx >= len(clips) - 4:      # leave a few clips untouched so the review queue is not empty
            continue
        for s in ctx.repo.list_suggestions(t["id"]):
            gold = _GOLD.get(s["original"])
            if s["kind"] == "normalization" or (gold and s["replacement"] == gold):
                review.decide(ctx, s["id"], "accepted", "demo-reviewer")
            else:
                review.decide(ctx, s["id"], "rejected", "demo-reviewer")
        raw = t["transcript_raw"]
        ref = " ".join(_GOLD.get(w, w) for w in raw.split())
        if idx % 3 == 0:               # a word the (synthetic) STT missed, so 'after' is not trivially perfect
            ref += " missedword"
        review.verify_reference(ctx, clip["id"], ref, "demo-reviewer")
    logger.info("Demo data seeded: %s", ctx.repo.counts())
    return {"seeded": True, **ctx.repo.counts()}
