def ingest(ctx, path, **kw):
    return ingest_file(ctx, path, os.path.basename(path), **kw)


def add_clip(ctx, make_tone, freq, **kw):
    return ingest(ctx, make_tone(freq), **kw).clips[0]


def wait(client, path, done=("completed", "failed", "rejected"), timeout=15):
    end = time.time() + timeout
    while time.time() < end:
        r = client.get(path).json()
        if r["status"] in done:
            return r
        time.sleep(0.1)
    raise AssertionError("run did not finish: " + json.dumps(r)[:300])


def snapshot(ctx):
    all_sugg = [s for t in sum((ctx.repo.list_transcripts(c["id"]) for c in ctx.repo.list_clips()), [])
                for s in ctx.repo.list_suggestions(t["id"])]
    return {"refs": [(c["id"], c["reference_transcript"], c["review_status"]) for c in ctx.repo.list_clips()],
            # human decisions must never change; pending suggestions may be regenerated by propose_corrections
            "decided": sorted((s["id"], s["status"], s["final_replacement"], s["decided_by"]) for s in all_sugg if s["status"] != "pending"),
            "pending_count": sum(1 for s in all_sugg if s["status"] == "pending"),
            "lex": ctx.repo.list_lexicon(), "perms": [(s["id"], s["permission_status"], s["permitted_usage"]) for s in ctx.repo.list_sources()]}


