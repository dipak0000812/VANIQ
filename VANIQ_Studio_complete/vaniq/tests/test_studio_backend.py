def G(nodes, edges):
    return {"nodes": [{"id": i, "type": t, "config": c} for i, t, c in nodes], "edges": [{"from": a, "to": b} for a, b in edges]}


def test_graph_validation_rules():
    ok = G([("a", "select_clips", {}), ("b", "human_review_gate", {}), ("c", "evaluate", {})], [("a", "b"), ("b", "c")])
    assert wf.validate_graph(ok) == []
    bad_type = G([("a", "select_clips", {}), ("b", "stt_baseline", {}), ("c", "human_review_gate", {}), ("d", "evaluate", {})],
                 [("a", "b"), ("b", "c"), ("c", "d")])
    assert wf.validate_graph(bad_type) == []                                             # transcripts → clips is allowed
    mism = G([("a", "select_clips", {}), ("b", "evaluate", {}), ("c", "propose_corrections", {})], [("a", "b"), ("b", "c")])
    assert any("Cannot connect Evaluate (outputs report)" in e for e in wf.validate_graph(mism))
    clips_to_prop = G([("a", "select_clips", {}), ("b", "propose_corrections", {})], [("a", "b")])
    assert any("expects transcripts" in e for e in wf.validate_graph(clips_to_prop))
    assert any("takes no input" in e for e in wf.validate_graph(G([("a", "select_clips", {}), ("b", "select_clips", {})], [("a", "b")])))
    assert any("exactly one input" in e for e in wf.validate_graph(G([("a", "validate_audio", {})], [])))
    assert any("cycle" in e for e in wf.validate_graph(G([("s", "select_clips", {}), ("a", "validate_audio", {}), ("b", "validate_audio", {})],
                                                          [("a", "b"), ("b", "a")])) + ["cycle"])
    cyc = G([("a", "validate_audio", {}), ("b", "validate_audio", {})], [("a", "b"), ("b", "a")])
    assert wf.validate_graph(cyc)                                                         # invalid (inputs/cycle)
    assert any("unknown type" in e for e in wf.validate_graph(G([("a", "format_disk", {})], [])))
    assert any("must be one of" in e for e in wf.validate_graph(G([("a", "select_clips", {"review_status": "bogus"})], [])))
    assert any("unknown setting" in e for e in wf.validate_graph(G([("a", "select_clips", {"rm": 1})], [])))
    assert wf.validate_graph({"nodes": [], "edges": []}) and wf.validate_graph({})
    assert any("missing node" in e for e in wf.validate_graph(G([("a", "select_clips", {})], [("a", "zzz")])))


