"""Demo-mode seed data. Everything here is SYNTHETIC: tone-burst audio, placeholder transcripts and
placeholder lexicon entries (dformN -> sformN). It contains no Ahirani/Marathi content and demonstrates
workflow mechanics only."""
from __future__ import annotations

import logging
